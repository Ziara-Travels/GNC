<script>
(function(){
  'use strict';
  if (window.__ztHeroInitEl) return;
  window.__ztHeroInitEl = true;

  var hero = document.getElementById('zt-hero-el');
  if (!hero) return;

  var slides = hero.querySelectorAll('.zt-slide');
  var dots   = hero.querySelectorAll('.zt-dot');
  var cur = 0, total = slides.length, timer = null, paused = false;

  function goTo(i) {
    cur = (i + total) % total;
    slides.forEach(function(s,j){ s.classList.toggle('is-active', j===cur); });
    dots.forEach(function(d,j)  { d.classList.toggle('is-active', j===cur); });
  }
  function start(){ stop(); timer = setInterval(function(){ if(!paused) goTo(cur+1); }, 7000); }
  function stop() { if(timer){ clearInterval(timer); timer=null; } }

  dots.forEach(function(d,i){ d.addEventListener('click', function(){ goTo(i); start(); }); });
  document.addEventListener('visibilitychange', function(){ paused = document.hidden; });

  var tx = 0;
  hero.addEventListener('touchstart', function(e){ tx = e.touches[0].clientX; }, {passive:true});
  hero.addEventListener('touchend',   function(e){
    var dx = e.changedTouches[0].clientX - tx;
    if (Math.abs(dx) > 50){ goTo(cur + (dx < 0 ? 1 : -1)); start(); }
  }, {passive:true});

  start();
})();
</script>